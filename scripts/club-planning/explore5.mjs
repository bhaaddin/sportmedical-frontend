import { launch, newPage, login, shot, buttons, dropConfirm, toasts, clickCard, findOrMakeClub, startClubOrder } from './lib.mjs';
const b = await launch();
const p = await newPage(b, 'desktop');
await login(p);
const club = await findOrMakeClub(p);
await startClubOrder(p, club.id, { 'Základní sportovní prohlídka': 7, 'Komplexní sportovní prohlídka': 5 });
await clickCard(p, 'Základní sportovní prohlídka');
await p.waitForTimeout(400);
await dropConfirm(p, { day: 0, min: 8 * 60 }, { min: 12 * 60 + 40 });
await shot(p, 'x-past-1');
await clickCard(p, 'Komplexní sportovní prohlídka');
await dropConfirm(p, { day: 1, min: 8 * 60 }, { min: 13 * 60 });
await shot(p, 'x-past-2');

console.log('toast', await toasts(p));
await p.locator('[data-summary-back]').click().catch((e) => console.log('no summary back', e.message.slice(0, 80)));
await p.waitForTimeout(800);
await shot(p, 'x-past-3');
console.log((await buttons(p)).filter((x) => !x.startsWith('mini-day')).slice(-14).join('\n'));
await b.close();
