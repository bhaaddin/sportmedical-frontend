import { launch, newPage, login, api, shot, waitPlanner, controlsIn, BASE } from './lib.mjs';
const b = await launch();
const p = await newPage(b, 'desktop');
await login(p);
const clubs = (await api(p, 'GET', '/api/clubs')).json;
const club = clubs.find((c) => c.name === 'ZZ test plánování');
await p.goto(`${BASE}/clubs/${club.id}`);
await waitPlanner(p);
await p.click('[data-testid=deck-empty-new]');
await p.waitForTimeout(1000);
await p.click('[data-testid=entry-phone]');
await p.waitForTimeout(1000);
await p.getByRole('combobox', { name: /Služba/ }).click().catch(async () => { await p.locator('[role=dialog] [role=combobox]').nth(1).click(); });
await p.waitForTimeout(600);
console.log((await p.$$eval('[role=option]', (e) => e.map((x) => x.innerText))).join(' / '));
await p.locator('[role=option]').first().click();
await p.waitForTimeout(1500);
await shot(p, 'x-setup2');
console.log((await controlsIn(p, '[role=dialog]')).join('\n'));
await b.close();
