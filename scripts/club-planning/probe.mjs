import { launch, newPage, login, api } from './lib.mjs';
const b = await launch();
const p = await newPage(b);
await login(p);
const clubs = (await api(p, 'GET', '/api/clubs')).json;
console.log('clubs', clubs.map((c) => `${c.id.slice(0,8)} ${c.name} active=${c.isActive}`).join('\n'));
const orders = (await api(p, 'GET', '/api/v1/club-orders')).json;
const arr = orders.data ?? orders;
console.log(Object.keys(arr[0]));
for (const o of arr) console.log(o.id.slice(0,8), o.clubName, o.status, o.serviceName, JSON.stringify((o.activities??o.activitySeats??[]).map(a=>`${a.name??a.activityId?.slice(0,6)}:${a.seats}`)), 'blocks', o.blocks?.length, o.blocks?.[0]?.fromDate);
const acts = (await api(p, 'GET', '/api/activities')).json.data.activities;
console.log(acts.map(a=>`${a.id.slice(0,8)} ${a.name} ${a.durationMinutes}m cap=${a.parallelCapacity} active=${a.isActive} svc=${a.clinicServiceId?.slice(0,6)}`).join('\n'));
await b.close();
