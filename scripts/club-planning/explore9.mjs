import { launch, newPage, login, shot, controlsIn, BASE, waitPlanner } from './lib.mjs';
const b = await launch();
const p = await newPage(b, 'desktop');
await login(p);
await p.goto(`${BASE}/planovani`);
await waitPlanner(p);
await p.getByRole('button', { name: 'Měsíc', exact: true }).first().click();
await p.waitForTimeout(600);
for (let i = 0; i < 3; i++) { await p.getByRole('button', { name: 'Následující měsíc' }).first().click(); await p.waitForTimeout(500); }
console.log(await p.locator('.alternative-head').first().innerText());
const a = await p.locator('.month-tile[data-day="2027-01-12"]').boundingBox();
const c = await p.locator('.month-tile[data-day="2027-01-14"]').boundingBox();
await p.mouse.move(a.x + a.width / 2, a.y + a.height / 2);
await p.mouse.down();
await p.mouse.move(c.x + c.width / 2, c.y + c.height / 2, { steps: 8 });
await p.mouse.up();
await p.waitForTimeout(800);
await shot(p, 'x-std-month-popover');
console.log((await p.$$eval('[role=menuitem], [role=menu] button, [role=dialog] button', (e) => e.map((x) => x.innerText.trim().replace(/\s+/g, ' ')))).join(' | '));
await p.getByText('Přidat do objednávky klubu').first().click();
await p.waitForTimeout(1200);
await shot(p, 'x-std-add-to-club');
console.log((await controlsIn(p, '[role=dialog]')).join('\n'));
await b.close();
