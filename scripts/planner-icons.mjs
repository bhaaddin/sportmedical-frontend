/*
 * Generates src/planner/components/IconSprite.generated.tsx from the
 * <symbol id="icon-*"> set of design/planner-v65.html.
 *
 *     node scripts/planner-icons.mjs
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const html = readFileSync(join(root, 'design', 'planner-v65.html'), 'utf8');
const sprite = /<svg aria-hidden="true"[^>]*class="svg-sprite">([\s\S]*?)<\/svg>/.exec(html);
if (!sprite) throw new Error('sprite not found');
const symbols = [...sprite[1].matchAll(/<symbol id="icon-([\w-]+)" viewBox="([^"]+)">([\s\S]*?)<\/symbol>/g)];
if (!symbols.length) throw new Error('no symbols');
const names = symbols.map((m) => m[1]);
const body = symbols
  .map((m) => `    <symbol id="icon-${m[1]}" viewBox="${m[2]}">${m[3].trim()}</symbol>`)
  .join('\n');
const out = `/* GENERATED by scripts/planner-icons.mjs from design/planner-v65.html - do not edit by hand. */

/** Names of the \`<symbol id="icon-NAME">\` entries of the sprite. */
export const ICON_NAMES = ${JSON.stringify(names)} as const;
export type IconName = (typeof ICON_NAMES)[number];

/** The sprite itself; rendered once by \`<Icons />\`. */
export function IconSymbols() {
  return (
    <>
${body}
    </>
  );
}
`;
writeFileSync(join(root, 'src', 'planner', 'components', 'IconSprite.generated.tsx'), out, 'utf8');
console.log(`${names.length} icons: ${names.join(', ')}`);
