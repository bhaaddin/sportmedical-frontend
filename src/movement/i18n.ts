export type Lang = 'cs' | 'en';

/** The language of the screens: Czech unless the clinic switched the module to English. */
export function moveLang(): Lang {
  try {
    return typeof localStorage !== 'undefined' && localStorage.getItem('sm-movement-lang') === 'en' ? 'en' : 'cs';
  } catch {
    return 'cs';
  }
}

export type Vars = Record<string, string | number>;

export function moveT(key: MoveKey, vars?: Vars, lang: Lang = moveLang()): string {
  const text = (lang === 'en' ? en : cs)[key];
  if (vars === undefined) return text;
  return text.replace(/\{(\w+)\}/g, (_, name: string) => (name in vars ? String(vars[name]) : `{${name}}`));
}

/** A key that may not exist (a messageKey from the pipeline): the fallback when it is unknown. */
export function moveTMaybe(key: string, fallback: string, vars?: Vars, lang: Lang = moveLang()): string {
  return key in cs ? moveT(key as MoveKey, vars, lang) : fallback;
}

export function useMoveT() {
  const lang = moveLang();
  return {
    lang,
    t: (key: MoveKey, vars?: Vars) => moveT(key, vars, lang),
    maybe: (key: string, fallback: string, vars?: Vars) => moveTMaybe(key, fallback, vars, lang),
  };
}

export const dateLocale = (lang: Lang = moveLang()): string => (lang === 'en' ? 'en-GB' : 'cs-CZ');
export const formatDate = (iso: string, lang: Lang = moveLang()): string => {
  const d = new Date(iso);
  return Number.isNaN(d.getTime()) ? iso : d.toLocaleDateString(dateLocale(lang));
};
export const formatDateTime = (iso: string, lang: Lang = moveLang()): string => {
  const d = new Date(iso);
  return Number.isNaN(d.getTime()) ? iso : d.toLocaleString(dateLocale(lang), { dateStyle: 'short', timeStyle: 'short' });
};
