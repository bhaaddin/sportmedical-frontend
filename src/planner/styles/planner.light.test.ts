/*
 * The planner's light stylesheet (R15e) is GENERATED from its dark stylesheets (scripts/planner-light-css.mjs). These tests keep it
 * honest: it is never stale, it can only ever match in light mode (so dark stays pixel-identical), it leaves the dark files alone,
 * and the colour translation keeps text readable.
 */
import { readFileSync } from 'node:fs';
import { join } from 'node:path';
import postcss from 'postcss';
import { describe, expect, it } from 'vitest';
import { LIGHT, SOURCES, build, toLight, translateValue } from '../../../scripts/planner-light-css.mjs';
import { contrastRatio, parseColor, type Rgba } from '../../accent';

const read = (rel: string): string => readFileSync(join(process.cwd(), rel), 'utf8');
const light = read('src/planner/styles/planner.light.css');
const rgb = (hex: string): Rgba => parseColor(hex) as Rgba;
const NAVY = '#001421';

describe('planner.light.css is generated and current', () => {
  it('equals what the generator writes now (run `node scripts/planner-light-css.mjs` after a planner stylesheet changes)', () => {
    expect(light).toBe(build());
  });
  it('carries the GENERATED banner and every rule hangs on html[data-sm-mode="light"]', () => {
    expect(light).toMatch(/GENERATED by scripts\/planner-light-css\.mjs/);
    const selectors: string[] = [];
    postcss.parse(light).walkRules((rule) => {
      if (rule.parent?.type === 'atrule' && /keyframes$/.test((rule.parent as postcss.AtRule).name)) return;
      selectors.push(...rule.selectors);
    });
    expect(selectors.length).toBeGreaterThan(1000);
    for (const one of selectors) expect(one.trim().startsWith(LIGHT), one).toBe(true);
  });
  it('translates every stylesheet of the planner (the sources exist and the list covers all planner CSS files)', () => {
    for (const rel of SOURCES) expect(read(rel).length).toBeGreaterThan(0);
  });
  it('never mentions the dark-only generated variable shift (no rule can re-introduce the cyan)', () => {
    expect(light).not.toMatch(/--sm-hsl/);
  });
});

describe('the colour translation', () => {
  it('turns near-white text into the ink and keeps the accent chrome as accent ink', () => {
    expect(toLight(rgb('#f4faff'), 'text')).toBe('#1A1D21');
    expect(toLight(rgb('#00e6e4'), 'text')).toContain('--sm-accent-ink');
  });
  it('keeps the contrast of AA text: every dark-theme text colour that read on the navy page reads on white', () => {
    for (const hex of ['#a3b9ce', '#bcd0e1', '#ffc857', '#ff7b98', '#6db5ff', '#b98bff', '#4df2da', '#7c93a8', '#d6eaf4']) {
      const out = toLight(rgb(hex), 'text') as string;
      if (out.startsWith('var(')) continue; /* the accent chrome: the accent ink, AA by accentInk */
      expect(out.startsWith('#'), out).toBe(true);
      const before = contrastRatio(hex, NAVY);
      const after = contrastRatio(out, '#FFFFFF');
      expect(after, `${hex} -> ${out}`).toBeGreaterThanOrEqual(Math.min(before, 4.5) - 0.2);
    }
  });
  it('turns a navy surface into a light one, a white veil into an ink veil, a black scrim into a light ink scrim', () => {
    expect(contrastRatio(toLight(rgb('#001a2a'), 'surface') as string, '#FFFFFF')).toBeLessThan(1.15);
    expect(toLight({ r: 255, g: 255, b: 255, a: 0.07 }, 'surface')).toBe('rgba(20, 24, 28, 0.07)');
    expect(toLight({ r: 0, g: 0, b: 0, a: 0.6 }, 'surface')).toBe('rgba(20, 24, 28, 0.24)');
  });
  it('makes glows far fainter and the accent a halo', () => {
    expect(translateValue('box-shadow', '0 0 21px #00d8dd2a')).toContain('--sm-accent');
    expect(translateValue('box-shadow', '0 7px 23px #0009')).toBe('0 7px 23px rgba(20, 24, 28, 0.096)');
  });
  it('leaves masks, urls and colourless values alone', () => {
    expect(translateValue('mask-image', 'linear-gradient(#000, transparent)')).toBeNull();
    expect(translateValue('background', 'url(#grad) no-repeat')).toBeNull();
    expect(translateValue('display', 'flex')).toBeNull();
  });
});
