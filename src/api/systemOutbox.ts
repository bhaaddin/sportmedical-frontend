/* ══════════════════════════════════════════════════════════════
   The e-mail queue, read-only.

     GET /api/system/outbox?take=   (settings.clinic.manage)

   A message is generated and queued even when no SMTP server is set up, so
   the owner can read what would be sent instead of taking it on trust.
   Nothing here sends, retries or deletes.
   ══════════════════════════════════════════════════════════════ */

import { client } from './client';

export interface OutboxMessage {
  id: string;
  to: string;
  subject: string;
  /** The HTML the message would be sent as. Ours, generated by the server. */
  body: string;
  /** `pending`, `sent` or `failed`. */
  status: string;
  /** The status in Czech: čeká na odeslání, odesláno, nepodařilo se odeslat. */
  statusLabel: string;
  attempts: number;
  lastError: string | null;
  createdAtUtc: string;
  sentAtUtc: string | null;
  /** Which message it is: booking-confirmation, booking-rescheduled, … */
  templateCode: string | null;
}

export interface OutboxQueue {
  items: OutboxMessage[];
  /** How many are still waiting, across the whole queue. */
  pending: number;
  /** False means nothing leaves until SMTP is set up — say so on the screen. */
  senderConfigured: boolean;
}

export const OUTBOX_QUERY_KEY = ['system', 'outbox'] as const;

export const readOutbox = async (take = 100): Promise<OutboxQueue> => {
  /* api/client.ts has already unwrapped the { success, data } envelope. */
  const { data } = await client.get<OutboxQueue>('/api/system/outbox', { params: { take } });
  return data;
};

/** What a person reads beside a message of this template. */
export const TEMPLATE_LABELS: Record<string, string> = {
  'booking-confirmation': 'Potvrzení termínu pacientovi',
  'booking-rescheduled': 'Přesun termínu pacientovi',
  'booking-cancelled': 'Zrušení termínu pacientovi',
  'booking-patient-rescheduled': 'Pacient přesunul termín — ordinaci',
  'booking-patient-cancelled': 'Pacient zrušil termín — ordinaci',
  'intake-link': 'Odkaz k dokončení registrace',
  'intake.confirmation': 'Potvrzení registrace',
};

export const templateLabel = (code: string | null): string =>
  (code !== null && TEMPLATE_LABELS[code]) || (code ?? 'Zpráva');
